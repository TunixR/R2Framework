"""Custom evaluators for R2Framework RecoveryBench."""

from __future__ import annotations

import json
from collections import Counter
from typing import Any, override

from pydantic import BaseModel
from strands import Agent as StrandsAgent
from strands_evals.evaluators import Evaluator
from strands_evals.types.evaluation import EvaluationData, EvaluationOutput
from tenacity import retry, stop_after_attempt


def _parse_output(output: Any) -> dict[str, Any] | None:
    """Parse task function output (may be str JSON or dict)."""
    if isinstance(output, dict):
        return output
    try:
        return json.loads(str(output))
    except (json.JSONDecodeError, TypeError):
        return None


class RoutingEvaluator(Evaluator[str, str]):
    """Deterministic evaluator for Contribution 1: Error Filtering.

    The task function returns {"is_ui_error": bool} based on which mock
    tool the Gateway Orchestrator called. Compares against GT directly.

    Metrics (at experiment level): precision, recall, F1 on is_ui_error.
    """

    @retry(stop=stop_after_attempt(3), reraise=True)
    @override
    def evaluate(
        self, evaluation_case: EvaluationData[str, str]
    ) -> list[EvaluationOutput]:
        expected = json.loads(evaluation_case.expected_output or "{}")
        actual = _parse_output(evaluation_case.actual_output)

        if actual is None:
            return [
                EvaluationOutput(
                    score=0.0,
                    test_pass=False,
                    reason=f"Could not parse agent output: {str(evaluation_case.actual_output)[:200]}",
                    label="UNPARSEABLE",
                )
            ]

        expected_val = expected.get("is_ui_error")
        actual_val = actual.get("is_ui_error")

        if actual_val is None:
            return [
                EvaluationOutput(
                    score=0.0,
                    test_pass=False,
                    reason="Agent output missing 'is_ui_error' field.",
                    label="MISSING",
                )
            ]

        match = actual_val == expected_val
        return [
            EvaluationOutput(
                score=1.0 if match else 0.0,
                test_pass=match,
                reason=f"Expected is_ui_error={expected_val}, got {actual_val}",
                label="CORRECT" if match else "WRONG",
            )
        ]

    @override
    async def evaluate_async(
        self, evaluation_case: EvaluationData[str, str]
    ) -> list[EvaluationOutput]:
        return self.evaluate(evaluation_case)


class TaskIdentificationEvaluator(Evaluator[str, str]):
    """LLM-as-judge evaluator for Task Identification.

    Uses the JUDGE_PROMPT from the notebook to evaluate on two axes:
    - Validity: Can a human execute the recovery correctly with the given context?
    - Extensiveness: insufficient / optimal / extensive

    No numeric score — returns validity bool + extensiveness label.
    """

    def __init__(self, judge_model: Any = None) -> None:
        super().__init__()
        self.judge_model = judge_model

    @retry(stop=stop_after_attempt(3), reraise=True)
    @override
    def evaluate(
        self, evaluation_case: EvaluationData[str, str]
    ) -> list[EvaluationOutput]:
        from prompts.task_inference import JUDGE_PROMPT

        expected = json.loads(evaluation_case.expected_output or "{}")
        actual = _parse_output(evaluation_case.actual_output)

        if actual is None:
            return [
                EvaluationOutput(
                    score=0.0,
                    test_pass=False,
                    reason=f"Could not parse agent output: {str(evaluation_case.actual_output)[:200]}",
                    label="UNPARSEABLE",
                )
            ]

        generated_task = actual.get("generated_task", "")

        if not generated_task:
            return [
                EvaluationOutput(
                    score=0.0,
                    test_pass=False,
                    reason="No recovery task generated by agent.",
                    label="EMPTY",
                )
            ]

        # Parse the input payload to reconstruct the judge context
        input_payload = json.loads(evaluation_case.input)

        class JudgeOutput(BaseModel):
            reasoning: str
            reflections: str
            validity: bool
            extensiveness: str

        judge = StrandsAgent(
            model=self.judge_model,
            system_prompt=JUDGE_PROMPT,
            callback_handler=None,
        )

        # Build judge prompt matching the notebook format
        ui_log = input_payload.get("ui_log", [])
        errored_act = input_payload.get("errored_act", {})

        prompt = (
            f"task_name: {input_payload.get('task_name', '')},\n"
            f"platform={input_payload.get('platform', '')},\n"
            f"os={input_payload.get('os', '')},\n"
            f"variables={json.dumps(input_payload.get('variables', {}))},\n"
            f"ui_log={json.dumps(ui_log)},\n"
            f"errored_act={json.dumps(errored_act)},\n"
            f"generated_task: {generated_task},\n"
            f"explanation: {expected.get('explanation', '')}"
        )

        result = judge(prompt, structured_output_model=JudgeOutput).structured_output

        validity = result.validity  # pyright: ignore[reportOptionalMemberAccess,reportAttributeAccessIssue]
        extensiveness = result.extensiveness  # pyright: ignore[reportOptionalMemberAccess,reportAttributeAccessIssue]
        reasoning = result.reasoning  # pyright: ignore[reportOptionalMemberAccess,reportAttributeAccessIssue]

        # Normalize extensiveness
        extensiveness = extensiveness.lower().strip() if extensiveness else "unknown"
        if extensiveness not in ("insufficient", "optimal", "extensive"):
            extensiveness = "unknown"

        if not validity:
            score = 0.0
            label = "INVALID"
        else:
            score = 1.0
            label = extensiveness.upper()

        return [
            EvaluationOutput(
                score=score,
                test_pass=validity,
                reason=f"[{label}] {reasoning}",
                label=label,
            )
        ]

    @override
    async def evaluate_async(
        self, evaluation_case: EvaluationData[str, str]
    ) -> list[EvaluationOutput]:
        return self.evaluate(evaluation_case)

    def evaluate_with_consensus(
        self,
        evaluation_case: EvaluationData[str, str],
        iterations: int = 1,
    ) -> tuple[list[EvaluationOutput], list[str]]:
        """Run the judge multiple times and return a consensus result with votes.

        Returns (evaluation_outputs, individual_label_votes).
        For iterations=1, votes is a single-element list.
        """
        if iterations <= 1:
            result = self.evaluate(evaluation_case)
            label = result[0].label or "UNKNOWN" if result else "UNKNOWN"
            return result, [label]

        results = [self.evaluate(evaluation_case)[0] for _ in range(iterations)]

        validity_votes = [r.test_pass for r in results if r.test_pass]
        label_votes = [r.label for r in results if r.label is not None]

        majority_valid = (
            Counter(validity_votes).most_common(1)[0][0] if validity_votes else False
        )
        consensus_label = (
            Counter(label_votes).most_common(1)[0][0] if label_votes else "UNKNOWN"
        )

        consensus_reason = (
            f"Consensus over {iterations} iterations: "
            f"validity={majority_valid}, label={consensus_label}. "
            f"Votes: {dict(Counter(label_votes))}"
        )

        return [
            EvaluationOutput(
                score=1.0 if majority_valid else 0.0,
                test_pass=majority_valid,
                reason=consensus_reason,
                label=consensus_label,
            )
        ], label_votes
